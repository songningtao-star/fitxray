"""
fitxray —— 体成分变化归因工具

体脂秤每天给你一堆数字，没有一个告诉你**这些数字的误差有多大**。
所以你会对着 0.4 kg 的跳动高兴或者焦虑 —— 而那个跳动大概率只是昨晚少喝了水。

这个工具做三件事：

    1. noise.py          从你自己的数据里估出噪声地板，不写死常量
    2. comparability.py  相减之前先门控 —— 这两次测量到底能不能比
    3. verdict.py        把不确定度传播到派生量，然后告诉你
                         那个「0.88 kg 的减脂」其实完全在噪声里

它不声称自己准。它声称自己对不确定性诚实 ——
而这两件事里，只有后者是能做到的。

模块划分：
    loaders        读测量记录和体征档案
    schema         数据模型、派生量、不确定度传播
    noise          噪声地板（变差函数 + 稳健估计 + LSC）
    comparability  可比性门控（ESPEN 标准化清单）
    verdict        综合判定（含多重比较校正）
    synth          带 ground truth 的合成数据生成
    evaluate       在合成数据上量化评测
    report         生成自包含 HTML 报告
    cli            命令行入口
"""

