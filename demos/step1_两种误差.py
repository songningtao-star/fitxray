"""
第 1 步：体脂秤的两个数字，误差根本不是一回事。

    python demos/step1_两种误差.py

这个脚本不 import fitxray —— 它把观测模型摊开写出来，
好让你能一行一行地核对"误差是怎么进去的"。

要看的结论：
    体重  的误差是**随机**的 —— 多测几次取平均，它会收敛
    体脂率 的误差是**方法**的 —— 测一百次也不会更准

后面所有推导都建在这条区分上。
"""

import numpy as np

# ---- 观测模型 ----------------------------------------------------------
# 真值 → 读数之间隔着一层。这一层就是本项目的全部立论来源。
TE_WEIGHT = 0.5      # 体重的日间波动标准差（kg）—— 随机的
METHOD_BF = 3.0      # 体脂率的**方法**误差标准差（百分点）—— 系统性的
N = 20000


def main():
    rng = np.random.default_rng(0)

    truth = 25.0  # 假设真实体脂率一直是 25%，一个人 60 天什么也没变
    readings = truth + rng.normal(0.0, METHOD_BF, N)

    print("=" * 70)
    print("同一个人的体脂率，真值恒定为 25.0%")
    print("=" * 70)
    print()

    # --- 1. 体脂率：读数散开了多少 ---------------------------------------
    lo, hi = np.percentile(readings, [2.5, 97.5])
    print("① 体脂率读数分布")
    print(f"   95% 的读数落在 {lo:.1f}% ~ {hi:.1f}% 之间")
    print(f"   也就是说：真值 25.0% 的人，秤会报出 19% 到 31% 的任何一个数。")
    print()

    # --- 2. 关键的一问：多测几次会变准吗 ---------------------------------
    #
    # 这里是最容易想错的一步。直觉是"多测几次取平均就更准了"。
    # 对**随机**误差成立，对**方法**误差不成立 ——
    # 因为方法误差跟着测量时的身体状态走，每次状态都不同，
    # 你没有一个"同一个东西"可以反复测。
    print("② 多测几次会变准吗？")
    print()
    for k in (1, 5, 30, 200):
        # 随机误差：k 次平均后标准差降到 1/√k
        random_err = TE_WEIGHT / np.sqrt(k)
        # 方法误差：每一次测量都是一个**新的身体状态**，
        # 平均掉的只是当天的状态，方法本身的偏差一点都不动
        method_err = METHOD_BF
        print(f"   测 {k:3d} 次：体重误差 {random_err:.3f} kg   "
              f"体脂率误差 {method_err:.1f} 个百分点")
    print()
    print("   → 体重那一列在往 0 收，体脂率那一列纹丝不动。")
    print("     这不是数据不够，是 BIA 这台设备本身达不到那个分辨率。")
    print()

    # --- 3. 传播到脂肪质量 ------------------------------------------------
    #
    # 脂肪质量 = 体重 × 体脂率 / 100。
    # 体脂率那一项压倒性地主导 —— 我们算一下到底差多少。
    print("③ 传播到脂肪质量（78 kg 的人，体脂率 25%）")
    w, pct = 78.2, 0.25
    rel_w = TE_WEIGHT / 78.2
    rel_p = METHOD_BF / 25.0

    print(f"   体重那一项贡献的相对不确定度：{rel_w:.4f}（{rel_w * 100:.2f}%）")
    print(f"   体脂率那一项贡献的相对不确定度：{rel_p:.4f}（{rel_p * 100:.1f}%）")
    print(f"   两者相差 {rel_p / rel_w:.0f} 倍 —— 体重那一项基本可以忽略")
    print()

    fat = w * pct
    half = fat * np.sqrt(rel_w ** 2 + rel_p ** 2)
    print(f"   脂肪质量 ≈ {fat:.2f} kg，方法不确定度 ≈ ±{half:.2f} kg")
    print()
    print("   → 你算得再准，也没法回答「我到底减了 0.5 kg 没有」，")
    print("     因为这台设备根本给不出 0.5 kg 的分辨率。")
    print()

    # --- 4. 那个让人误判的例子 -------------------------------------------
    print("④ 体脂秤最常骗人的一幕")
    print()
    a_w, a_p = 78.2, 25.0
    b_w, b_p = 77.8, 24.0
    a_fat = a_w * a_p / 100
    b_fat = b_w * b_p / 100
    print(f"   {a_w} kg / {a_p}% → 脂肪 {a_fat:.3f} kg")
    print(f"   {b_w} kg / {b_p}% → 脂肪 {b_fat:.3f} kg")
    print(f"   看起来减掉了 {a_fat - b_fat:.3f} kg 脂肪 —— 秤会这么告诉你。")
    print()
    print(f"   但方法不确定度是 ±{half:.2f} kg 量级。")
    print(f"   {a_fat - b_fat:.3f} kg 只有它的 {(a_fat - b_fat) / half * 100:.0f}%。")
    print()
    print("   这个变化完全读不出来。不是数据不够 —— 是方法本身达不到。")
    print()
    print("=" * 70)
    print("下一步：demos/step2_噪声地板.py —— 那「变化」到底多大才算数？")
    print("=" * 70)


if __name__ == "__main__":
    main()
